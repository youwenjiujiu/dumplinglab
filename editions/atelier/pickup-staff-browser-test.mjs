import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { randomUUID, randomBytes } from 'node:crypto';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import '../../web/server/order-core.js';
const output=await mkdtemp(join(tmpdir(),'pickup-staff-'));
const origin='http://127.0.0.1:7898';
const api=async (path, input)=>{const r=await fetch(origin+path,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(input)});const out=await r.json();assert(r.ok,JSON.stringify(out));return out;};
const d=MENU.find(d=>!d.styles&&!d.soldOut&&d.price>=5);
const input={action:'checkout',requestId:randomUUID(),token:randomBytes(32).toString('hex'),mode:'takeaway',items:[{id:d.id,qty:1}],pickupLocation:'preview-store'};
await api('/api/online',input);
await api('/api/online',{action:'preview-pay',requestId:input.requestId,token:input.token});
const response=await fetch(`${origin}/api/online?id=${input.requestId}`,{headers:{authorization:`Bearer ${input.token}`}});
const {order}=await response.json();assert(order.pickup);
const qrFile=join(output,'pickup.png');await writeFile(qrFile,Buffer.from(order.pickup.qr.split(',')[1],'base64'));
const decoded=(await promisify(execFile)('/usr/bin/swift',[new URL('./decode-pickup-qr.swift',import.meta.url).pathname,qrFile],{timeout:120000})).stdout.trim();
assert.equal(decoded,`${origin}/staff.html#pickup=${order.id}.${order.pickup.code}`,'independent QR decoder recovers the exact order credential');
assert(!decoded.includes(input.token),'QR never exposes the private order access token');
const browser=await chromium.launch({channel:'chrome'});
try {
  const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(decoded);
  await page.locator('#collectPickup').waitFor();
  assert((await page.locator('#pickupResult').innerText()).includes(order.pickup.number));
  assert.equal(new URL(page.url()).hash,'','credential removed from address bar after capture');
  let current=await api('/api/pickup',{action:'inspect',id:order.id,code:order.pickup.code});
  assert.equal(current.order.collectedAt,undefined,'scanning alone does not hand over the order');
  await page.locator('#collectPickup').click();
  await page.waitForFunction(()=>document.querySelector('#pickupResult').textContent.includes('已取餐'));
  current=await api('/api/pickup',{action:'inspect',id:order.id,code:order.pickup.code});
  assert(current.order.collectedAt);
  await page.goto(decoded);
  await page.waitForFunction(()=>document.querySelector('#pickupResult').textContent.includes('请勿重复交餐'));
  assert.equal(await page.locator('#collectPickup').count(),0);
  assert.deepEqual(errors,[]);
  await page.screenshot({path:join(output,'staff-collected.png')});
} finally {await browser.close();}
console.log('PASS independent QR decode, staff inspection, explicit collection, repeat-scan prevention');
console.log(output);
