import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {createTableStore} from '../../web/server/table-state.js';
let clock=Date.now();
const yesterday=new Date(clock-86400000).toISOString(),today=new Date(clock).toISOString();
const op=at=>({id:randomUUID(),deviceId:randomUUID(),table:'D3',group:'A',kind:'delta',dishId:'lunch-v2-barley',delta:1,at});
const oldOp=op(yesterday),newOp=op(today),oldOrder={id:randomUUID(),type:'order',at:yesterday,status:'paid',no:'4030'};
let state={table:'D3',group:'A',revision:'r',sequence:0,operations:[oldOp,newOp],events:[oldOrder],activity:[oldOp,newOp]};
const store=createTableStore({read:async()=>({value:structuredClone(state),etag:'r'}),write:async(p,value)=>{state=value},isConflict:()=>false,all:async()=>[state]}, {feed:async()=>({events:[],activeIds:[]})},{now:()=>clock});
const cart=await store.cart('D3','A');
assert.equal(cart.orders.length,0);assert.equal(cart.items[0].qty,1);assert.deepEqual(cart.opIds,[newOp.id]);assert.equal(cart.activity.length,1);
assert.equal(state.events.length,1);assert.equal(state.operations.length,2);assert((await store.feed()).events.some(o=>o.id===oldOrder.id));
const order={id:randomUUID(),tokenHash:'hash',table:'D3',group:'A',items:cart.items,cartOpIds:[oldOp.id],note:null};
await assert.rejects(store.reservePayment(order),e=>e.code==='CHECKOUT_CART_CHANGED');
assert.equal(state.paymentHold,undefined);
await store.reservePayment({...order,cartOpIds:cart.opIds});
assert.equal(state.paymentHold.id,order.id);
clock+=86400000;
const next=await store.cart('D3','A',cart.version);
assert.notEqual(next.version,cart.version);assert.equal(next.items.length,0);assert.equal(next.paymentPending,true,'unverified payments remain protected');
await store.finishPayment({...state.paymentHold,status:'paid',at:today});
assert.equal(state.events.length,2,'late paid receipt retained in ledger');
assert.equal(state.paymentHold,undefined);
assert.equal((await store.cart('D3','A')).orders.length,0);
console.log('PASS table day: Singapore date isolation, stale operation rejection, day-aware version, preserved staff ledger and safe late payment.');
